async fn handle_command_error(
    ctx: &mut ConnectionContext,
    cmd_id: CmdId,
    up_tag: u8,
    error: AppError,
) -> Result<(), AppError> {
    let is_unhandled = matches!(error, AppError::Cmd(CmdError::UnhandledCmd(_)));
    let action = error.client_action();
    let result_code = match action {
        ClientErrorAction::Reply(code) | ClientErrorAction::Reconnect(code) => code,
    };
    let client_message = match (&error, action) {
        (AppError::Cmd(CmdError::UnhandledCmd(_)), _) => {
            format!("{cmd_id:?} is not implemented")
        }
        (_, ClientErrorAction::Reply(_)) => format!("{cmd_id:?}: {error}"),
        (_, ClientErrorAction::Reconnect(_)) => {
            format!("{cmd_id:?} failed; reconnecting to restore client state")
        }
    };
    match action {
        ClientErrorAction::Reply(_) => tracing::warn!(
            command = ?cmd_id,
            result_code = result_code.id(),
            "Request rejected: {error}"
        ),
        ClientErrorAction::Reconnect(_) => tracing::error!(
            command = ?cmd_id,
            result_code = result_code.id(),
            "Command failed; reconnecting client: {error}"
        ),
    }

    ctx.notify(
        CmdId::ServerErrorInfoPushCmd,
        ServerErrorInfoPush {
            msg: Some(client_message),
            is_alert: Some(!is_unhandled),
        },
    )
    .await?;
    ctx.send_empty_reply(cmd_id, Vec::new(), result_code.id(), up_tag)
        .await?;
    if matches!(action, ClientErrorAction::Reconnect(_)) {
        ctx.request_disconnect();
    }
    Ok(())
}
