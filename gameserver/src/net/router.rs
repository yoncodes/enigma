macro_rules! dispatch {
    ($cmd_id:expr, $ctx:expr, $packet:expr, {
        $($variant:path => $handler:expr),* $(,)?
    }) => {
        match $cmd_id {
            $(
                $variant => $handler($ctx, $packet).await,
            )*
            v => Err(AppError::Cmd(CmdError::UnhandledCmd(v))),
        }
    };
}

