pub(super) fn get(id: i32) -> Option<&'static ActivitySchedule> {
    ACTIVE
        .binary_search_by_key(&id, |row| row.id)
        .ok()
        .map(|index| &ACTIVE[index])
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn schedule_is_sorted_and_unique() {
        assert_eq!(ACTIVE.len(), 130);
        assert!(ACTIVE.windows(2).all(|rows| rows[0].id < rows[1].id));
    }

    #[test]
    fn authoritative_rows_match_their_windows_and_unlocks() {
        let expected = [
            (
                1786615200000,
                2145934800000,
                false,
                &[12801, 12810, 12811, 13006, 13011, 13015][..],
            ),
            (1786615200000, 2145934800000, true, &[12802, 13007][..]),
            (
                1786615200000,
                1790243999000,
                true,
                &[
                    13209, 13702, 13704, 13710, 13714, 13715, 13716, 13718, 13720, 13721, 13724,
                    13728, 13729, 13730, 13731, 13732, 13733, 13734, 13737, 13739, 13740, 13742,
                    13746,
                ][..],
            ),
            (1786615200000, 1789984799000, true, &[13703, 13706][..]),
            (1786615200000, 1788429599000, true, &[13725][..]),
            (
                1785664800000,
                1789811999000,
                true,
                &[138508, 138510, 138511, 138527][..],
            ),
        ];

        assert_eq!(
            expected
                .iter()
                .map(|(_, _, _, ids)| ids.len())
                .sum::<usize>(),
            38
        );

        for (start_time, end_time, is_unlock, ids) in expected {
            for id in ids {
                let row = get(*id).unwrap();
                assert_eq!(
                    (row.start_time, row.end_time, row.is_unlock),
                    (start_time, end_time, is_unlock)
                );
            }
        }
    }
}
